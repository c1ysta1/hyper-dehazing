from pathlib import Path

CHUNK = 64 * 1024 * 1024  # 64MB


def dos_datetime(dt):
    """ZipInfo.date_time -> DOS time/date words"""
    dos_time = (dt[3] << 11) | (dt[4] << 5) | (dt[5] // 2)
    dos_date = ((dt[0] - 1980) << 9) | (dt[1] << 5) | dt[2]
    return dos_time, dos_date


def build_central_dir(infos, drop):
    """?????????????????????????????????(header_offset ?????? drop) + EOCD, ?????? (bytes, cd_size)"""
    cd = bytearray()
    n = len(infos)
    for info in infos:
        fname = info.filename.encode('utf-8')
        extra = info.extra if info.extra else b''
        comment = info.comment if info.comment else b''
        dos_t, dos_d = dos_datetime(info.date_time)
        offset = info.header_offset - drop
        entry = struct.pack(
            '<IHHHHHHIIIHHHHHII',
            0x02014b50,              # signature
            info.create_version,     # version made by
            20,                      # version needed (2.0)
            info.flag_bits,
            info.compress_type,
            dos_t,
            dos_d,
            info.CRC,
            info.compress_size,
            info.file_size,
            len(fname),
            len(extra),
            len(comment),
            0,                       # disk number start
            info.internal_attr,
            info.external_attr,
            offset,
        )
        cd += entry + fname + extra + comment
    cd_size = len(cd)
    return bytes(cd), cd_size


def slim_zip(path, drop, rest_infos):
    """???????????? zip ?????? drop ??????, ?????????????????????"""
    with open(path, 'rb+') as f:
        size = os.path.getsize(path)
        remaining = size - drop
        # ?????????????????? [drop, size) -> [0, remaining)
        src = size
        dst = remaining
        while src > drop:
            chunk = min(CHUNK, src - drop)
            src -= chunk
            dst -= chunk
            f.seek(src)
            buf = f.read(chunk)
            f.seek(dst)
            f.write(buf)
        f.truncate(remaining)
        # ????????????????????????(?????????????????????) + EOCD
        cd_bytes, cd_size = build_central_dir(rest_infos, drop)
        f.seek(0, 2)
        cd_offset = f.tell()
        f.write(cd_bytes)
        eocd = struct.pack(
            '<IHHHHIIH',
            0x06054b50,
            0, 0,
            len(rest_infos), len(rest_infos),
            cd_size,
            cd_offset,
            0,
        )
        f.write(eocd)
        f.flush()
        os.fsync(f.fileno())


def extract_batch(zip_path, out_dir, batch_infos):
    """??????????????????; ??????????????????????????????(??????)"""
    with zipfile.ZipFile(zip_path) as zf:
        for info in batch_infos:
            # info.filename = 'train/xxx.npy'
            name = Path(info.filename)
            rel = name.parts[1] if len(name.parts) > 1 else name.name
            dst = Path(out_dir) / rel
            if dst.exists() and dst.stat().st_size == info.file_size:
                continue
            data = zf.read(info)  # ???CRC??????
            dst.write_bytes(data)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--zip', required=True)
    ap.add_argument('--out', required=True)
    ap.add_argument('--batch', type=int, default=300)
    args = ap.parse_args()

    zip_path = Path(args.zip)
    out_dir = Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)

    with zipfile.ZipFile(zip_path) as zf:
        infos = [i for i in zf.infolist() if not i.is_dir()]
    total = len(infos)
    print(f'????????????: {total}', flush=True)

    processed = 0
    t0 = time.time()
    while processed < total:
        batch = infos[processed:processed + args.batch]
        # 1. ????????????
        extract_batch(zip_path, out_dir, batch)
        processed += len(batch)
        dt = time.time() - t0
        print(f'[?????? {processed}/{total}] ????????? {len(batch)} ???, ?????? {dt:.0f}s', flush=True)

        rest = infos[processed:]
        if not rest:
            break
        # 2. ????????????????????? zip ???????????? = ???????????????????????? header_offset
        drop = rest[0].header_offset
        if drop <= 0:
            continue
        # 3. ?????? zip
        slim_zip(zip_path, drop, rest)
        free = os.statvfs(out_dir)
        free_gb = free.f_bavail * free.f_frsize / 1e9
        print(f'   zip ????????? (-{drop/1e9:.1f}GB), ???????????? {free_gb:.0f}GB', flush=True)

    zip_path.unlink(missing_ok=True)
    print(f'??????: ?????? {total} ?????????, ????????? train.zip, ????????? {time.time()-t0:.0f}s', flush=True)


if __name__ == '__main__':
    main()
